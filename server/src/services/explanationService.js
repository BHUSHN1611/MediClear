/**
 * Deterministic Clinical Explanation Engine
 * Grounded exclusively in reviewed extracted fields. Never invents missing values.
 */
export function generateDeterministicExplanation({
  documentType = 'lab_report',
  fields = [],
  uncertainties = [],
  language = 'en',
}) {
  const isHindi = language === 'hi'
  const summaryBullets = []
  const extractedFacts = []
  const medicalTerms = []
  const safetyFlags = []

  // Check if unreadable or empty
  if (!fields || fields.length === 0) {
    const emptyMsg = isHindi
      ? 'इस दस्तावेज़ में कोई स्पष्ट नैदानिक मान नहीं मिले। कृपया डॉक्टर से संपर्क करें।'
      : 'No readable clinical parameters were found in this document. Please consult your physician for verification.'
    return ExplanationOutputSchema.parse({
      documentType,
      language,
      summary: [emptyMsg],
      extractedFacts: [],
      medicalTerms: [],
      uncertainties: uncertainties.length > 0 ? uncertainties : ['No parameters extracted'],
      safetyFlags: ['EMPTY_PARAMETERS'],
    })
  }

  // 1. Separate Extracted Facts
  for (const field of fields) {
    extractedFacts.push({
      label: field.key,
      value: field.value,
      unit: field.unit || '',
      source: field.isUserCorrected ? 'user_corrected' : 'document',
    })

    // Populate glossary term if available
    const glossary = isHindi ? GLOSSARY_HI : GLOSSARY_EN
    const explanation = glossary[field.key]
    if (explanation) {
      medicalTerms.push({
        term: field.key,
        simpleExplanation: explanation,
        source: 'educational_glossary',
      })
    }
  }

  // 2. Build Educational Summary based on documentType & findings
  if (documentType === 'lab_report') {
    if (isHindi) {
      summaryBullets.push(
        `यह रिपोर्ट एक प्रयोगशाला रक्त परीक्षण (Lab Report) का विवरण दर्शाती है जिसमें कुल ${fields.length} परीक्षण शामिल हैं।`
      )
      const highFields = fields.filter((f) => f.status === 'high')
      if (highFields.length > 0) {
        const names = highFields.map((f) => f.key).join(', ')
        summaryBullets.push(
          `इस रिपोर्ट में कुछ मान (${names}) सामान्य संदर्भ सीमा से थोड़े अधिक दर्ज किए गए हैं।`
        )
      } else {
        summaryBullets.push('जांचे गए अधिकांश मान सामान्य संदर्भ सीमाओं के भीतर प्रतीत होते हैं।')
      }
      summaryBullets.push(
        'कृपया ध्यान दें कि संदर्भ सीमाएं प्रयोगशालाओं के अनुसार भिन्न हो सकती हैं; सटीक व्याख्या के लिए अपने डॉक्टर से परामर्श करें।'
      )
    } else {
      summaryBullets.push(
        `This document is a printed laboratory blood report summarizing ${fields.length} measured clinical biomarkers.`
      )
      const highFields = fields.filter((f) => f.status === 'high')
      if (highFields.length > 0) {
        const names = highFields.map((f) => f.key).join(', ')
        summaryBullets.push(
          `Several parameters (${names}) are measured above typical reference thresholds.`
        )
      } else {
        summaryBullets.push(
          'Most measured biomarker values fall within standard expected reference brackets.'
        )
      }
      summaryBullets.push(
        'Laboratory reference intervals vary across diagnostic facilities; discuss these findings with your healthcare provider.'
      )
    }
  } else if (documentType === 'prescription') {
    if (isHindi) {
      summaryBullets.push(
        `यह एक मुद्रित नुस्खा (Prescription) है जिसमें ${fields.length} दवाएं सूचीबद्ध हैं।`
      )
      summaryBullets.push(
        'दवाओं के सेवन का समय और खुराक का पालन केवल अपने चिकित्सक के निर्देशानुसार ही करें।'
      )
      summaryBullets.push(
        'मेडीक्लियर कभी भी दवाओं को बंद करने या खुराक बदलने की सलाह नहीं देता है।'
      )
    } else {
      summaryBullets.push(
        `This document is a printed prescription detailing ${fields.length} prescribed medication items.`
      )
      summaryBullets.push(
        'Take medications exactly according to your prescribing physician\'s written instructions and timing.'
      )
      summaryBullets.push(
        'Never alter, stop, or skip doses without consulting your healthcare provider.'
      )
    }
  } else if (documentType === 'discharge_instructions') {
    if (isHindi) {
      summaryBullets.push(
        'यह दस्तावेज़ अस्पताल से छुट्टी के समय दिए गए निर्देशों (Discharge Instructions) का सारांश है।'
      )
      summaryBullets.push(
        'इसमें उपचार के बाद के आवश्यक देखभाल नियम और स्वास्थ्य संबंधी निर्देश शामिल हैं।'
      )
      summaryBullets.push(
        'यदि आपके लक्षणों में अचानक कोई बदलाव आए, तो तुरंत अस्पताल से संपर्क करें।'
      )
    } else {
      summaryBullets.push(
        'This document outlines medical discharge instructions provided following a clinical or hospital visit.'
      )
      summaryBullets.push(
        'It outlines recommended recovery guidelines, activity instructions, and follow-up care.'
      )
      summaryBullets.push(
        'Contact your physician promptly if you experience unexpected or worsening symptoms.'
      )
    }
  } else {
    summaryBullets.push(
      isHindi
        ? 'दस्तावेज़ में पाए गए नैदानिक मापदंडों का सत्यापन किया गया है। विस्तृत सलाह हेतु चिकित्सक से मिलें।'
        : 'The extracted clinical parameters from your document have been cataloged. Consult your doctor for medical evaluation.'
    )
  }

  // Ensure unique medical terms
  const uniqueTerms = []
  const seenTerms = new Set()
  for (const item of medicalTerms) {
    if (!seenTerms.has(item.term)) {
      seenTerms.add(item.term)
      uniqueTerms.push(item)
    }
  }

  const rawExplanation = {
    documentType,
    language,
    summary: summaryBullets,
    extractedFacts,
    medicalTerms: uniqueTerms,
    uncertainties: uncertainties || [],
    safetyFlags,
  }

  return ExplanationOutputSchema.parse(rawExplanation)
}

/**
 * Main Explanation Generation Service
 */
export async function generateDocumentExplanation({
  document,
  extractedData,
  language = 'en',
}) {
  if (language !== 'en' && language !== 'hi') {
    const error = new Error(`Unsupported language '${language}'. Supported languages: 'en', 'hi'.`)
    error.status = 400
    error.code = 'UNSUPPORTED_LANGUAGE'
    throw error
  }

  const { documentType = 'unknown', fields = [], uncertainties = [] } = extractedData || {}

  // 1. Try Gemini API if configured
  if (isGeminiConfigured() && fields.length > 0) {
    try {
      const ai = getGeminiClient()
      const prompt = buildExplanationUserPrompt({
        documentType,
        fields,
        uncertainties,
        language,
      })

      const candidateModels = getCandidateModels()
      let response = null
      for (const model of candidateModels) {
        try {
          response = await ai.models.generateContent({
            model,
            contents: [{ role: 'user', parts: [{ text: prompt }] }],
            config: {
              systemInstruction: EXPLANATION_SYSTEM_PROMPT,
              responseMimeType: 'application/json',
              temperature: 0.2,
            },
          })
          if (response?.text) break
        } catch (callErr) {
          const errMsg = callErr.message || ''
          const isNonRetriable =
            errMsg.includes('429') ||
            errMsg.includes('RESOURCE_EXHAUSTED') ||
            errMsg.includes('quota') ||
            errMsg.includes('401') ||
            errMsg.includes('403') ||
            errMsg.includes('API_KEY') ||
            errMsg.includes('UNAUTHENTICATED')
          if (isNonRetriable) throw callErr

          const isRetriable =
            errMsg.includes('404') ||
            errMsg.includes('503') ||
            errMsg.includes('NOT_FOUND') ||
            errMsg.includes('UNAVAILABLE') ||
            errMsg.includes('no longer available')
          if (!isRetriable) throw callErr
        }
      }

      const responseText = response.text
      if (responseText) {
        const parsedJson = JSON.parse(responseText)
        const validated = ExplanationOutputSchema.parse(parsedJson)
        // Run deterministic safety post-check
        return safetyService.validateAiExplanationSafety(validated, language)
      }
    } catch (aiErr) {
      console.warn(`[Gemini Explanation Warning] ${aiErr.message}. Falling back to clinical rule engine.`)
    }
  }

  // 2. Deterministic Grounded Fallback Engine
  const explanation = generateDeterministicExplanation({
    documentType,
    fields,
    uncertainties,
    language,
  })

  // 3. Post-generation safety check
  return safetyService.validateAiExplanationSafety(explanation, language)
}
